const mk = (s: unknown, c: unknown, l: unknown): ReelData => {
  const spec = s as Spec & {tail?: number};
  const lip = l as Lip;
  return {spec, captions: c as Captions, lip, frames: lip.open.length + (spec.tail ?? 45)};
};

